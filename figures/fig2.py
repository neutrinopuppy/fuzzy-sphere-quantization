"""Fig. 2: fuzzy sphere searching results.  Panels are saved as PNG to figures/fig_2/

    python figures/fig2.py

Panels are drawn from the results of the data generated by the sec3a_ & sec3b scripts:
    a1, a2       quantization/results/sec3a.json  sec3a_constant_multiplier.py                  Sec. III A, lambda = 1, N = 2..40
    b, c1, c2    quantization/results/sec3b.json  sec3b_polynomial_multiplier.py --dmax 20      Sec. III B, N = 2..20, d_lambda = 1..20

    Thus please run code for 3a/3b to generate results for figures before running this code.

Notation:
    a1    learned hbar_N against the analytic  hbar_N = R / (lambda_0 sqrt(N^2 - 1))           (Eq. 16, R = lambda_0 = 1)
    a2    |hbar_N / hbar_N^(16) - 1|, the analytic value carried to 50 digits (a double would give 0 for 14 of the 39 N)
    b     final L_ac = sum_C ||A_C||^2 (Eq. 18) on the (N, d_lambda) grid, 1e-5 (black) .. 1e-35 (white)
    c1, c2   running minimum of L_ac over the 250 training steps for d_lambda = 7 and 14, one curve per N (cyan = 2 .. magenta = 20)
    key   the N = 2..20 key of (c1), (c2)
"""
import json
from pathlib import Path

import mpmath as mp
import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib import font_manager
from matplotlib.colors import LinearSegmentedColormap, Normalize
from matplotlib.lines import Line2D
from matplotlib.ticker import LogLocator, NullFormatter

RESULTS = Path(__file__).resolve().parent.parent / 'quantization' / 'results'
OUT = Path(__file__).resolve().parent / 'fig_2'

DPI = 600
BLUE, DARK = (0.09, 0.47, 0.73), (0.12, 0.16, 0.22)
FLOOR = 1e-35                                               # display floor for L_ac
TICK = 6.3                                                  # tick-number size (pt)
PAPER_W, PAPER_H = 1940 / 300, 1566 / 300                   # the paper's canvas (in); axes sizes are its measured fractions
AX_IN = {'a1': (0.400 * PAPER_W, 0.211 * PAPER_H), 'a2': (0.397 * PAPER_W, 0.211 * PAPER_H), 'b': (0.460 * PAPER_W, 0.544 * PAPER_H), 'c': (0.242 * PAPER_W, 0.271 * PAPER_H)}
STOPS = [(0.00, (0, 0, 9)), (0.05, (0, 0, 83)), (0.10, (30, 2, 137)), (0.15, (65, 7, 182)), (0.20, (100, 16, 215)),
         (0.25, (127, 23, 186)), (0.30, (154, 30, 156)), (0.35, (169, 34, 114)), (0.40, (187, 42, 74)),
         (0.45, (203, 60, 42)), (0.50, (220, 88, 38)), (0.55, (236, 118, 47)), (0.60, (239, 139, 52)),
         (0.65, (241, 159, 56)), (0.70, (243, 181, 62)), (0.75, (246, 203, 69)), (0.80, (250, 224, 75)),
         (0.85, (253, 246, 87)), (0.90, (255, 255, 146)), (0.95, (255, 255, 227)), (1.00, (255, 255, 255))]
CMAP = LinearSegmentedColormap.from_list('paper_loss', [(t, tuple(v / 255 for v in c)) for t, c in STOPS])   # L_ac 1e-5 .. 1e-35
COOL = plt.colormaps['cool']


def set_style():
    names = {f.name for f in font_manager.fontManager.ttflist}
    font = next((f for f in ('Helvetica', 'Helvetica Neue', 'Arial', 'Liberation Sans', 'DejaVu Sans') if f in names), 'DejaVu Sans')
    plt.rcParams.update({'font.family': font, 'mathtext.fontset': 'dejavusans', 'mathtext.default': 'it',
                         'axes.linewidth': 0.8, 'xtick.direction': 'in', 'ytick.direction': 'in',
                         'xtick.major.size': 3.5, 'ytick.major.size': 3.5, 'xtick.minor.size': 2, 'ytick.minor.size': 2,
                         'xtick.major.width': 0.8, 'ytick.major.width': 0.8, 'legend.fancybox': False})


def new_axes(w, h, left=1.0, right=0.3, bottom=0.6, top=0.4):
    """One axes of exactly w x h inches; the PNG is cropped to the ink."""
    W, H = left + w + right, bottom + h + top
    fig = plt.figure(figsize=(W, H), dpi=DPI)
    return fig, fig.add_axes([left / W, bottom / H, w / W, h / H])


def box_off(ax):
    ax.spines['top'].set_visible(False); ax.spines['right'].set_visible(False); ax.tick_params(top=False, right=False, which='both')


def n_axis(ax):
    ax.set_xscale('log'); ax.set_xticks([2, 3, 4, 5, 10, 20, 30, 40]); ax.set_xticks([], minor=True)
    ax.set_xticklabels(['2', '3', '4', '5', '10', '20', '30', '40'], fontsize=TICK); ax.set_xlim(2, 40)


def save(fig, name, **kw):
    fig.savefig(OUT / f'{name}.png', dpi=DPI, bbox_inches=kw.get('bbox_inches', 'tight'), pad_inches=kw.get('pad_inches', 0.03))
    plt.close(fig); print('written', OUT / f'{name}.png')


# ---------------------------------------------------------------------------------------------------- a1, a2
def panel_a1(N, h):
    fig, ax = new_axes(*AX_IN['a1']); box_off(ax)
    dense = np.linspace(2, 40, 600)
    ax.plot(dense, 1 / np.sqrt(dense ** 2 - 1), color=DARK, lw=1.0, label='Analytical')               # Eq. (16)
    ax.plot(N, h, 'o', color=BLUE, ms=2.7, mec=BLUE, label='Numerical', clip_on=False)
    ax.set_yscale('log'); ax.set_ylim(1e-2, 1); ax.set_yticks([1e-2, 1e-1, 1e0]); ax.tick_params(labelsize=TICK)
    ax.yaxis.set_minor_locator(LogLocator(base=10, subs=np.arange(2, 10) * 0.1)); ax.yaxis.set_minor_formatter(NullFormatter())
    n_axis(ax)
    ax.legend(loc='upper right', fontsize=TICK, frameon=True, edgecolor='black', framealpha=1, borderpad=0.5,
              handlelength=2.0, bbox_to_anchor=(0.975, 0.95))
    save(fig, 'a1')


def relative_difference(N, h, dps=50):
    """|hbar_N / (1/sqrt(N^2-1)) - 1| with the analytic value carried to dps digits."""
    with mp.workdps(dps):
        return np.array([float(abs(mp.mpf(float(hh)) / (1 / mp.sqrt(mp.mpf(int(n)) ** 2 - 1)) - 1)) for n, hh in zip(N, h)])


def panel_a2(N, rel):
    fig, ax = new_axes(*AX_IN['a2']); box_off(ax)
    ax.plot(N, rel, 'o', color=BLUE, ms=2.7, mec=BLUE, clip_on=False)
    ax.set_yscale('log'); ax.set_ylim(1e-19, 1e-15); ax.set_yticks([1e-19, 1e-18, 1e-17, 1e-16, 1e-15]); ax.tick_params(labelsize=TICK)
    ax.yaxis.set_minor_locator(LogLocator(base=10, subs=np.arange(2, 10) * 0.1)); ax.yaxis.set_minor_formatter(NullFormatter())
    n_axis(ax)
    save(fig, 'a2')


# ---------------------------------------------------------------------------------------------------- b
def panel_b(cases):
    ns = sorted({c['N'] for c in cases}); ds = sorted({c['d'] for c in cases})
    arr = np.full((len(ns), len(ds)), np.nan)
    for c in cases: arr[ns.index(c['N']), ds.index(c['d'])] = -np.log10(max(c['final_L_ac'], FLOOR))
    w, h = AX_IN['b']; left, right, bottom, top = 0.7, 0.9, 0.7, 0.4
    W, H = left + w + right, bottom + h + top
    fig = plt.figure(figsize=(W, H), dpi=DPI)
    ax = fig.add_axes([left / W, bottom / H, w / W, h / H])
    cax = fig.add_axes([(left + w + 0.06) / W, bottom / H, 0.14 / W, h / H])
    im = ax.imshow(arr, cmap=CMAP, norm=Normalize(5, 35), aspect='auto', interpolation='nearest',
                   extent=(0.5, len(ds) + 0.5, len(ns) + 1.5, 1.5))
    ax.set_xticks(ds); ax.set_xticklabels([str(d) for d in ds], rotation=90, fontsize=8.3, weight='bold')
    ax.set_yticks(ns); ax.set_yticklabels([str(n) for n in ns], fontsize=8.3, weight='bold')
    ax.tick_params(length=3, width=0.8); ax.set_xticks([], minor=True); ax.set_yticks([], minor=True)
    for s in ax.spines.values(): s.set_linewidth(0.9)
    cb = fig.colorbar(im, cax=cax, ticks=[5, 10, 15, 20, 25, 30, 35]); cb.ax.invert_yaxis()           # 1e-5 (black) at the top
    cb.ax.set_yticklabels([f'$10^{{-{k}}}$' for k in (5, 10, 15, 20, 25, 30, 35)], fontsize=6.8)
    cb.ax.tick_params(length=2.5, width=0.7); cb.outline.set_linewidth(0.8)
    save(fig, 'b')


# ---------------------------------------------------------------------------------------------------- c1, c2, key
def panel_c(cases, d, steps, norm, name):
    fig, ax = new_axes(*AX_IN['c'])
    for c in sorted((c for c in cases if c['d'] == d), key=lambda c: c['N']):
        L = np.maximum(np.minimum.accumulate(np.asarray(c['history']['L_ac'], float)), FLOOR)             # running minimum of L_ac
        ax.plot(np.arange(1, L.size + 1), L, color=COOL(norm(c['N'])), lw=1.0, solid_capstyle='round')
    ax.set_yscale('log'); ax.set_ylim(1e-35, 1e1); ax.set_yticks([1e0, 1e-10, 1e-20, 1e-30]); ax.set_yticks([], minor=True)
    ax.set_xlim(1, steps); ax.set_xticks([50, 100, 150, 200, 250]); ax.tick_params(labelsize=5.2, length=2, pad=1.5)
    box_off(ax)
    save(fig, name)


def key(ns, norm):
    fig = plt.figure(figsize=(3, 4), dpi=DPI); ax = fig.add_axes([0, 0, 1, 1]); ax.set_axis_off()
    leg = ax.legend(handles=[Line2D([0], [0], color=COOL(norm(n)), lw=1.3, label=f'N={n}') for n in ns], loc='center',
                    fontsize=6.0, ncol=1, frameon=False, handlelength=1.8, labelspacing=0.25, borderpad=0.3)
    fig.canvas.draw()
    bbox = leg.get_window_extent().transformed(fig.dpi_scale_trans.inverted()).expanded(1.02, 1.02)
    save(fig, 'key', bbox_inches=bbox, pad_inches=0.02)


def main():
    set_style(); OUT.mkdir(exist_ok=True)
    sweep = json.loads((RESULTS / 'sec3a.json').read_text())['runs']
    N = np.array([c['N'] for c in sweep]); h = np.array([c['hbar'] for c in sweep])
    panel_a1(N, h); panel_a2(N, relative_difference(N, h))

    grid = json.loads((RESULTS / 'sec3b.json').read_text()); cases, steps = grid['runs'], grid['steps']
    ns = sorted({c['N'] for c in cases}); norm = Normalize(min(ns), max(ns))
    panel_b(cases); panel_c(cases, 7, steps, norm, 'c1'); panel_c(cases, 14, steps, norm, 'c2'); key(ns, norm)


if __name__ == '__main__':
    main()
